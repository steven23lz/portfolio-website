import * as React from "react"
import { cn } from "@/lib/utils"

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { spotlight?: boolean }
>(({ className, spotlight = true, onMouseMove, ...props }, ref) => {
  const handleMouseMove = (e: React.MouseEvent<HTMLDivElement>) => {
    if (spotlight) {
      const rect = e.currentTarget.getBoundingClientRect()
      e.currentTarget.style.setProperty("--mouse-x", `${e.clientX - rect.left}px`)
      e.currentTarget.style.setProperty("--mouse-y", `${e.clientY - rect.top}px`)
    }
    onMouseMove?.(e)
  }

  return (
    <div
      ref={ref}
      onMouseMove={handleMouseMove}
      className={cn(
        "rounded-2xl border border-border/70 bg-card/80 text-card-foreground shadow-xl backdrop-blur-xl transition-all duration-300",
        spotlight && "spotlight-card",
        className
      )}
      {...props}
    />
  )
})
Card.displayName = "Card"

